"""Fixtures: ask Blender to generate the source files, and write a `.qc` for the compiler.

Fixtures are cached **per directory**: the directory name carries the scale
parameters, and `manifest.json` records the parameters and the paths of the
generated files. The same parameters reuse the directory, so Blender is not run
again (generating a 252k-triangle DMX takes four minutes).

Directory layout:

```
<work>/fixtures/<name>-s<subdiv>-m<morphs>-t<materials>-f<frames>/
    mesh.dmx | mesh.smd | mesh.fbx
    anims/idle.dmx | idle.smd          (FBX keeps the animation in the same file)
    fixture.qc
    manifest.json
```
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path

from .config import BENCH_DIR, Config, ConfigError, Fixture

#: The generator script that runs inside Blender.
MAKE_FIXTURE = BENCH_DIR / "blender" / "make_fixture.py"


@dataclass
class FixturePaths:
    """A fixture that has been generated."""

    fixture: Fixture
    dir: Path
    mesh: Path
    anim: Path | None
    qc: Path

    @property
    def label(self) -> str:
        return self.fixture.name


def fixture_dir(config: Config, fixture: Fixture) -> Path:
    """The cache directory name carries every parameter that changes the output."""
    tag = (
        f"{fixture.name}-s{fixture.subdivisions}"
        f"-m{fixture.morphs}-t{fixture.materials}-f{fixture.sequence_frames}"
    )
    return config.general.work_dir / "fixtures" / tag


def _manifest_ok(path: Path, fixture: Fixture) -> dict | None:
    """Cache-hit test: same parameters and all files still present."""
    manifest_path = path / "manifest.json"
    if not manifest_path.is_file():
        return None
    try:
        data = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if data.get("params") != _params(fixture):
        return None
    for key in ("mesh", "qc"):
        if not Path(data.get(key, "")).is_file():
            return None
    anim = data.get("anim")
    if anim and not Path(anim).is_file():
        return None
    return data


def _params(fixture: Fixture) -> dict:
    return {
        "format": fixture.format,
        "subdivisions": fixture.subdivisions,
        "size": fixture.size,
        "morphs": fixture.morphs,
        "materials": fixture.materials,
        "sequence_frames": fixture.sequence_frames,
    }


def _qc_text(fixture: Fixture, mesh_name: str, anim_name: str | None) -> str:
    """Write a minimal compilable QC.

    FBX bakes the animation into the same file, so `$sequence` points at the
    mesh file too; for DMX / SMD the animation lives in its own file.
    """
    lines = [
        "// Generated by the mdlc benchmarks; do not edit.",
        f'$modelname "bench/{fixture.name}.mdl"',
        f'$body body "{mesh_name}"',
    ]
    if fixture.sequence_frames > 0:
        target = anim_name or mesh_name
        lines.append(f'$sequence idle "{target}" fps 30')
    return "\n".join(lines) + "\n"


def ensure(config: Config, fixture: Fixture, *, generate: bool = True) -> FixturePaths:
    """Get the fixture, running Blender first when needed."""
    directory = fixture_dir(config, fixture)
    cached = _manifest_ok(directory, fixture)
    if cached is not None:
        # Rewrite the `.qc` even on a cache hit: it depends only on the
        # configuration, never on the generated content, so an older fixture
        # must not keep a stale QC around after the generator changes.
        return _finish(fixture, directory, _paths_from_manifest(fixture, directory, cached))
    if not generate:
        raise ConfigError(
            f"fixture {fixture.name!r} has not been generated yet ({directory}), "
            "but --no-generate was given. Drop the flag, or generate it first."
        )

    directory.mkdir(parents=True, exist_ok=True)
    blender = config.blender.resolve()
    if not MAKE_FIXTURE.is_file():
        raise ConfigError(f"the generator script is missing: {MAKE_FIXTURE}")

    argv = [
        blender,
        "-b",
        "--python",
        str(MAKE_FIXTURE),
        "--",
        fixture.format,
        str(fixture.subdivisions),
        f"{fixture.size:g}",
        str(fixture.morphs),
        str(fixture.materials),
        str(fixture.sequence_frames),
        str(directory),
    ]
    print(f"  - generating fixture {fixture.name} ({fixture.describe()}) ...", end="", flush=True)
    started = time.perf_counter()
    try:
        proc = subprocess.run(
            argv,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=config.blender.timeout,
        )
    except subprocess.TimeoutExpired:
        raise ConfigError(
            f"Blender took longer than {config.blender.timeout:.0f} s to generate "
            f"{fixture.name!r}. Use a smaller scale, or raise [blender] timeout."
        ) from None
    except OSError as exc:
        raise ConfigError(f"could not start Blender: {exc}") from None

    elapsed = time.perf_counter() - started
    result = None
    for line in proc.stdout.splitlines():
        if line.startswith("RESULT "):
            result = line.split()
    if proc.returncode != 0 or result is None:
        tail = "\n".join((proc.stdout + proc.stderr).splitlines()[-20:])
        raise ConfigError(
            f"Blender failed to generate {fixture.name!r} (exit {proc.returncode}). "
            f"Last 20 lines:\n{tail}"
        )
    if len(result) >= 3 and result[1] == "ERROR":
        raise ConfigError(f"Blender reported an error: {' '.join(result[2:])}")

    mesh = Path(result[2])
    anim = None if len(result) < 4 or result[3] == "-" else Path(result[3])
    manifest = {
        "params": _params(fixture),
        "mesh": str(mesh),
        "anim": None if anim is None else str(anim),
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "blender": blender,
        "seconds": round(elapsed, 1),
    }

    paths = _finish(
        fixture,
        directory,
        FixturePaths(fixture=fixture, dir=directory, mesh=mesh, anim=anim,
                     qc=directory / "fixture.qc"),
    )
    manifest["qc"] = str(paths.qc)
    (directory / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f" {elapsed:.1f}s")
    return paths


def _finish(fixture: Fixture, directory: Path, paths: FixturePaths) -> FixturePaths:
    """Write the `.qc`; always rewritten, see the note in [`ensure`]."""
    # The animation path relative to the fixture directory: FBX bakes the
    # animation into the mesh file itself, so both are one file, while DMX / SMD
    # keep the animation under `anims/`.
    anim_name = None
    if paths.anim is not None:
        anim_name = paths.mesh.name if paths.anim == paths.mesh else f"anims/{paths.anim.name}"
    qc = directory / "fixture.qc"
    qc.write_text(
        _qc_text(fixture, paths.mesh.name, anim_name),
        encoding="utf-8",
        newline="\n",
    )
    return FixturePaths(
        fixture=fixture,
        dir=directory,
        mesh=paths.mesh,
        anim=paths.anim,
        qc=qc,
    )


def _paths_from_manifest(fixture: Fixture, directory: Path, data: dict) -> FixturePaths:
    anim = data.get("anim")
    return FixturePaths(
        fixture=fixture,
        dir=directory,
        mesh=Path(data["mesh"]),
        anim=None if not anim else Path(anim),
        qc=Path(data["qc"]),
    )


def check_blender(config: Config) -> str:
    """Resolve Blender up front so the failure happens before anything else runs."""
    if not sys.version_info >= (3, 11):  # pragma: no cover
        pass
    return config.blender.resolve()
